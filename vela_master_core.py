import os
import sys
import json
import subprocess
import urllib.request
import urllib.error

# Config Defaults & Environment Variables
SUPABASE_URL = os.getenv("SUPABASE_URL", "")
SUPABASE_KEY = os.getenv("SUPABASE_KEY", "")
GITHUB_REPO_DIR = os.getenv("GITHUB_REPO_DIR", ".")

# --- [A01: MAIN ENGINE - WAY NANO CORE & CONTENT STUDIO] ---
class VelaContentEngine:
    def __init__(self):
        self.engine_name = "Way Nano Core & Content Studio"

    def generate(self, prompt: str) -> dict:
        """สร้างโค้ดและเนื้อหาอัตโนมัติจาก Prompt"""
        print(f"⚡ [{self.engine_name}] กำลังประมวลผล Main Input: '{prompt}'...")
        
        # ตัวอย่างโครงสร้าง Output ที่สร้างขึ้นอัตโนมัติ
        return {
            "title": f"Vela_Module_{prompt.replace(' ', '_')}",
            "code": f"# Auto-generated by Vela System\ndef execute_task():\n    print('Task execute for: {prompt}')\n    return True\n",
            "documentation": f"เอกสารประกอบโมดูล {prompt} สำหรับระบบ Vela Core",
            "metadata": {
                "author": "Vela AI Engine",
                "version": "1.0.0",
                "target_platform": "Termux / Cloud Runtime"
            }
        }

# --- [Z01: QUALITY CHECK - 4 DIMENSIONS] ---
class QualityCheck4D:
    @staticmethod
    def inspect(output: dict) -> tuple[bool, dict]:
        """ตรวจสอบความสอดคล้อง 4 มิติ"""
        results = {
            "1_syntax_correctness": bool(output.get("code") and "def " in output["code"]),
            "2_structural_integrity": all(k in output for k in ["title", "code", "metadata"]),
            "3_security_safety": not any(danger in output.get("code", "") for danger in ["eval(", "exec(", "os.system('rm"]),
            "4_readability_completeness": len(output.get("code", "")) > 15
        }
        passed = all(results.values())
        return passed, results

# --- [B01 & Z02: PRIMARY MECHANISM & EXPORT TARGET NODES] ---
class VelaExporter:
    @staticmethod
    def export_to_supabase(data: dict) -> bool:
        """ส่งออกและบันทึกข้อมูลลง Supabase ผ่าน HTTP Standard Library"""
        if not SUPABASE_URL or not SUPABASE_KEY:
            print("⚠️ [Z02 SUPABASE] ข้ามการบันทึก: ไม่พบ SUPABASE_URL หรือ SUPABASE_KEY")
            return False
            
        endpoint = f"{SUPABASE_URL.rstrip('/')}/rest/v1/vela_logs"
        headers = {
            "apikey": SUPABASE_KEY,
            "Authorization": f"Bearer {SUPABASE_KEY}",
            "Content-Type": "application/json",
            "Prefer": "return=minimal"
        }
        
        try:
            req = urllib.request.Request(
                endpoint, 
                data=json.dumps(data).encode("utf-8"), 
                headers=headers, 
                method="POST"
            )
            with urllib.request.urlopen(req) as resp:
                if resp.status in [200, 201]:
                    print("💾 [Z02 EXPORT] บันทึกข้อมูลลง Supabase สำเร็จ")
                    return True
        except Exception as e:
            print(f"⚠️ [Z02 ERROR] บันทึก Supabase ไม่สำเร็จ: {e}")
        return False

    @staticmethod
    def export_to_github(filename: str, content: str) -> bool:
        """Commit และ Push โค้ดผ่าน Git Command บน Termux / Terminal"""
        try:
            filepath = os.path.join(GITHUB_REPO_DIR, filename)
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(content)
                
            # Git Pipeline Commands
            subprocess.run(["git", "-C", GITHUB_REPO_DIR, "add", filepath], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(["git", "-C", GITHUB_REPO_DIR, "commit", "-m", f"Vela Auto-Export: {filename}"], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(["git", "-C", GITHUB_REPO_DIR, "push"], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            print(f"🐙 [Z02 EXPORT] Push ไฟล์ '{filename}' ขึ้น GitHub เรียบร้อยครับ")
            return True
        except Exception as e:
            print(f"ℹ️ [Z02 EXPORT] สแนปช็อตไฟล์ในเครื่องสำเร็จ ('{filename}') - Git Push Bypass: {e}")
            return False

# --- [MAIN WORKFLOW PIPELINE WITH Z00 REVISION LOOP] ---
def run_vela_pipeline(prompt: str, max_retries: int = 3):
    print("==================================================")
    print("🚀 สตาร์ตระบบหลัก VELA MASTER CORE WORKFLOW")
    print("==================================================")
    
    engine = VelaContentEngine()
    attempt = 1
    
    while attempt <= max_retries:
        print(f"\n🔄 [LOOP {attempt}/{max_retries}] เริ่มต้นสร้างและตรวจเช็กคุณภาพ...")
        
        # A01 Output Generation
        output = engine.generate(prompt)
        
        # Z01 Quality Check
        passed, report = QualityCheck4D.inspect(output)
        
        if passed:
            print("✅ [Z01 PASS] ผ่านเกณฑ์ตรวจสอบความสอดคล้องทั้ง 4 มิติเรียบร้อย!")
            
            # Z02 Export Targets
            VelaExporter.export_to_supabase(output)
            file_name = f"{output['title'].lower()}.py"
            VelaExporter.export_to_github(file_name, output["code"])
            
            print("\n🎉 [WORKFLOW COMPLETE] ทำงานเสร็จสมบูรณ์เรียบร้อยครับพ่อ!")
            return output
        else:
            print(f"⚠️ [Z01 FAIL] ไม่ผ่านเกณฑ์ในรอบที่ {attempt}: {report}")
            print("🔁 [Z00 RETURN/BYPASS] ส่งกลับไปปรับปรุงแก้ไข (Target Node Revision)...")
            attempt += 1
            
    print("❌ [Z00 ERROR] ระบบปรับปรุงเกินจำนวนครั้งที่กำหนด")
    return None

if __name__ == "__main__":
    # Input คำสั่งทดสอบรันระบบ
    input_prompt = sys.argv[1] if len(sys.argv) > 1 else "Auto System Engine"
    run_vela_pipeline(input_prompt)
